"""
SAM Executive Briefing Generator (Epic 6).

Generates structured executive briefings from engine outputs and alert data.
Template-based generation — no AI required, though content is enriched
with SAM-style commentary.

Briefing types:
  morning          — daily morning summary (generated at ~06:00)
  daily            — end-of-day position summary
  weekly           — weekly position and trend summary
  monthly_board    — monthly board risk briefing
  quarterly_exec   — quarterly executive review
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum


class BriefingType(str, Enum):
    MORNING = "morning"
    DAILY = "daily"
    WEEKLY = "weekly"
    MONTHLY_BOARD = "monthly_board"
    QUARTERLY_EXEC = "quarterly_exec"

    @property
    def label(self) -> str:
        labels = {
            "morning": "Morning Briefing",
            "daily": "Daily Summary",
            "weekly": "Weekly Summary",
            "monthly_board": "Monthly Board Brief",
            "quarterly_exec": "Quarterly Executive Review",
        }
        return labels.get(self.value, self.value.replace("_", " ").title())


@dataclass
class BriefingKeyMetrics:
    lcr_ratio: float | None = None
    nsfr_ratio: float | None = None
    cet1_ratio: float | None = None
    tier1_ratio: float | None = None
    total_capital_ratio: float | None = None
    leverage_ratio: float | None = None
    snapshot_date: str | None = None
    currency: str = "USD"

    def to_dict(self) -> dict:
        return {
            "lcr_ratio": self.lcr_ratio,
            "nsfr_ratio": self.nsfr_ratio,
            "cet1_ratio": self.cet1_ratio,
            "tier1_ratio": self.tier1_ratio,
            "total_capital_ratio": self.total_capital_ratio,
            "leverage_ratio": self.leverage_ratio,
            "snapshot_date": self.snapshot_date,
            "currency": self.currency,
        }


@dataclass
class BriefingInput:
    entity_name: str
    briefing_type: str
    metrics: BriefingKeyMetrics
    alert_count: int = 0
    critical_alert_count: int = 0
    warning_alert_count: int = 0
    open_issue_count: int = 0
    active_recommendation_count: int = 0
    trend_summary: str = ""
    top_alerts: list[dict] = field(default_factory=list)
    top_recommendations: list[dict] = field(default_factory=list)
    prior_metrics: BriefingKeyMetrics | None = None


def _pct(v: float | None, multiply: bool = True) -> str:
    if v is None:
        return "—"
    val = v * 100 if multiply else v
    return f"{val:.2f}%"


def _ratio(v: float | None) -> str:
    if v is None:
        return "—"
    return f"{v:.4f}"


def _pass_fail(v: float | None, minimum: float) -> str:
    if v is None:
        return "N/A"
    return "✓ Pass" if v >= minimum else "✗ Fail"


def _health_summary(inputs: BriefingInput) -> str:
    m = inputs.metrics
    failures = sum([
        (m.lcr_ratio is not None and m.lcr_ratio < 1.0),
        (m.nsfr_ratio is not None and m.nsfr_ratio < 1.0),
        (m.cet1_ratio is not None and m.cet1_ratio < 0.045),
    ])
    if failures == 0 and inputs.critical_alert_count == 0:
        return "All key regulatory metrics are within prescribed limits. No critical alerts are active."
    elif failures == 1 or inputs.critical_alert_count == 1:
        return "One metric is approaching or breaching regulatory limits. Management review is required."
    else:
        return f"{failures} metric(s) require immediate management attention. Critical alerts are active."


def generate_briefing(inputs: BriefingInput) -> str:
    """
    Generate a Markdown executive briefing document from engine outputs.
    Returns a complete Markdown string.
    """
    now = datetime.now(tz=timezone.utc)
    bt = BriefingType(inputs.briefing_type) if inputs.briefing_type in [t.value for t in BriefingType] else BriefingType.DAILY
    m = inputs.metrics

    lines: list[str] = [
        f"# {bt.label} — {inputs.entity_name}",
        f"**Generated by SAM:** {now.strftime('%d %B %Y, %H:%M UTC')}",
        "",
    ]

    if m.snapshot_date:
        lines.append(f"**Snapshot Date:** {m.snapshot_date}")
        lines.append("")

    # ── Executive Summary ──────────────────────────────────────────────────
    lines += [
        "## Executive Summary",
        "",
        _health_summary(inputs),
        "",
    ]

    if inputs.alert_count > 0:
        lines.append(
            f"There are **{inputs.alert_count} active alerts** "
            f"({inputs.critical_alert_count} critical, {inputs.warning_alert_count} warning)."
        )
        lines.append("")

    if inputs.open_issue_count > 0:
        lines.append(f"**{inputs.open_issue_count} outstanding issue(s)** require attention.")
        lines.append("")

    # ── Key Metrics ────────────────────────────────────────────────────────
    lines += [
        "## Key Metrics",
        "",
        "| Metric | Value | Minimum | Status |",
        "|--------|-------|---------|--------|",
        f"| LCR | {_pct(m.lcr_ratio)} | 100.00% | {_pass_fail(m.lcr_ratio, 1.0)} |",
        f"| NSFR | {_pct(m.nsfr_ratio)} | 100.00% | {_pass_fail(m.nsfr_ratio, 1.0)} |",
        f"| CET1 | {_pct(m.cet1_ratio)} | 4.50% | {_pass_fail(m.cet1_ratio, 0.045)} |",
        f"| Tier 1 | {_pct(m.tier1_ratio)} | 6.00% | {_pass_fail(m.tier1_ratio, 0.06)} |",
        f"| Total Capital | {_pct(m.total_capital_ratio)} | 8.00% | {_pass_fail(m.total_capital_ratio, 0.08)} |",
        f"| Leverage | {_pct(m.leverage_ratio)} | 3.00% | {_pass_fail(m.leverage_ratio, 0.03)} |",
        "",
    ]

    # ── Material Changes ───────────────────────────────────────────────────
    if inputs.prior_metrics and inputs.trend_summary:
        lines += [
            "## Material Changes",
            "",
            inputs.trend_summary,
            "",
        ]

    # ── Top Risks ──────────────────────────────────────────────────────────
    lines += ["## Top Risks", ""]
    if inputs.top_alerts:
        for a in inputs.top_alerts[:5]:
            lines.append(
                f"- **{a.get('severity', '').upper()}** | {a.get('title', '')} — {a.get('message', '')}"
            )
    else:
        lines.append("No active risk alerts at this time.")
    lines.append("")

    # ── Recommended Actions ────────────────────────────────────────────────
    lines += ["## Recommended Actions", ""]
    if inputs.top_recommendations:
        for rec in inputs.top_recommendations[:5]:
            p = rec.get("priority", 3)
            lines.append(
                f"{p}. **{rec.get('title', '')}** ({rec.get('category', '').title()}) — "
                f"{rec.get('description', '')[:120]}…"
            )
    else:
        lines.append("Continue regular monitoring. No immediate actions required.")
    lines.append("")

    # ── Outstanding Issues ─────────────────────────────────────────────────
    lines += [
        "## Outstanding Issues",
        "",
        f"Open issues: **{inputs.open_issue_count}**",
        "",
    ]

    # ── Regulatory Status ──────────────────────────────────────────────────
    lcr_ok = m.lcr_ratio is None or m.lcr_ratio >= 1.0
    nsfr_ok = m.nsfr_ratio is None or m.nsfr_ratio >= 1.0
    cap_ok = m.cet1_ratio is None or m.cet1_ratio >= 0.045
    all_ok = lcr_ok and nsfr_ok and cap_ok

    lines += [
        "## Regulatory Status",
        "",
        f"**Overall Status:** {'Compliant' if all_ok else 'Non-Compliant — Review Required'}",
        "",
        "| Framework | Status |",
        "|-----------|--------|",
        f"| Basel III — LCR | {'✓ Compliant' if lcr_ok else '✗ Breach'} |",
        f"| Basel III — NSFR | {'✓ Compliant' if nsfr_ok else '✗ Breach'} |",
        f"| Basel III — Capital | {'✓ Compliant' if cap_ok else '✗ Breach'} |",
        "",
        "---",
        f"*Prepared by SAM — Senior Banking Intelligence Advisor. "
        f"All metrics sourced from validated engine outputs. "
        f"SAM does not compute regulatory ratios.*",
    ]

    return "\n".join(lines)
