import { useState } from "react";
import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { clsx } from "clsx";
import { Clock, Plus, Trash2, ToggleLeft, ToggleRight } from "lucide-react";
import { format } from "date-fns";

interface ScheduledReport {
  id: string;
  report_type: string;
  schedule_type: "daily" | "weekly" | "monthly";
  enabled: boolean;
  last_run: string | null;
  next_run: string | null;
  created_at: string;
  created_by: string;
}

interface ScheduledReportsResponse {
  configs: ScheduledReport[];
  total: number;
}

const REPORT_TYPES = [
  { value: "ceo_brief", label: "CEO Brief" },
  { value: "cro_report", label: "CRO Report" },
  { value: "board_pack", label: "Board Pack" },
  { value: "liquidity_risk", label: "Liquidity Risk" },
  { value: "capital_adequacy", label: "Capital Adequacy" },
  { value: "icaap", label: "ICAAP" },
  { value: "ilaap", label: "ILAAP" },
  { value: "stress_testing", label: "Stress Testing" },
  { value: "regulatory_compliance", label: "Regulatory Compliance" },
  { value: "executive_dashboard", label: "Executive Dashboard" },
];

const SCHEDULE_TYPES = [
  { value: "daily", label: "Daily" },
  { value: "weekly", label: "Weekly" },
  { value: "monthly", label: "Monthly" },
];

async function fetchSchedules(): Promise<ScheduledReportsResponse> {
  const r = await fetch("/api/v1/autonomous/scheduled-reports");
  if (!r.ok) return { configs: [], total: 0 };
  return r.json();
}

async function createSchedule(body: { report_type: string; schedule_type: string; enabled: boolean }): Promise<ScheduledReport> {
  const r = await fetch("/api/v1/autonomous/scheduled-reports", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  if (!r.ok) throw new Error("Failed to create schedule");
  return r.json();
}

async function toggleSchedule(id: string, enabled: boolean): Promise<void> {
  await fetch(`/api/v1/autonomous/scheduled-reports/${id}`, {
    method: "PATCH",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ enabled }),
  });
}

async function deleteSchedule(id: string): Promise<void> {
  await fetch(`/api/v1/autonomous/scheduled-reports/${id}`, { method: "DELETE" });
}

function scheduleColor(s: string) {
  if (s === "daily") return "bg-accent/15 text-accent";
  if (s === "weekly") return "bg-purple-500/15 text-purple-500";
  return "bg-green-500/15 text-green-500";
}

export function ScheduledReportsPage() {
  const qc = useQueryClient();
  const [showCreate, setShowCreate] = useState(false);
  const [form, setForm] = useState({ report_type: "ceo_brief", schedule_type: "weekly", enabled: true });

  const { data, isLoading } = useQuery({
    queryKey: ["scheduled-reports"],
    queryFn: fetchSchedules,
    staleTime: 60_000,
  });

  const createMutation = useMutation({
    mutationFn: createSchedule,
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ["scheduled-reports"] });
      setShowCreate(false);
      setForm({ report_type: "ceo_brief", schedule_type: "weekly", enabled: true });
    },
  });

  const toggleMutation = useMutation({
    mutationFn: ({ id, enabled }: { id: string; enabled: boolean }) => toggleSchedule(id, enabled),
    onSuccess: () => qc.invalidateQueries({ queryKey: ["scheduled-reports"] }),
  });

  const deleteMutation = useMutation({
    mutationFn: deleteSchedule,
    onSuccess: () => qc.invalidateQueries({ queryKey: ["scheduled-reports"] }),
  });

  const schedules = data?.configs ?? [];

  return (
    <div className="space-y-6 pb-8" data-testid="scheduled-reports-page">
      <div className="flex items-start justify-between">
        <div>
          <h1 className="text-xl font-bold text-text-primary dark:text-gray-100">
            Scheduled Reports
          </h1>
          <p className="text-body text-text-secondary dark:text-gray-400 mt-0.5">
            Configure recurring automated reports generated by SAM
          </p>
        </div>
        <button
          onClick={() => setShowCreate(!showCreate)}
          className="flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-body font-medium bg-accent text-white hover:bg-accent/90 transition-colors"
        >
          <Plus className="h-3.5 w-3.5" />
          Add Schedule
        </button>
      </div>

      {/* Create form */}
      {showCreate && (
        <div className="rounded-xl border border-border bg-surface p-4 space-y-3">
          <h3 className="text-body font-semibold text-text-primary">New Schedule</h3>
          <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
            <div className="space-y-1">
              <label className="text-caption text-text-secondary">Report Type</label>
              <select
                value={form.report_type}
                onChange={(e) => setForm({ ...form, report_type: e.target.value })}
                className="w-full rounded-md border border-border bg-surface px-2 py-1.5 text-body text-text-primary focus:outline-none focus:ring-1 focus:ring-accent"
              >
                {REPORT_TYPES.map((t) => (
                  <option key={t.value} value={t.value}>{t.label}</option>
                ))}
              </select>
            </div>
            <div className="space-y-1">
              <label className="text-caption text-text-secondary">Frequency</label>
              <select
                value={form.schedule_type}
                onChange={(e) => setForm({ ...form, schedule_type: e.target.value })}
                className="w-full rounded-md border border-border bg-surface px-2 py-1.5 text-body text-text-primary focus:outline-none focus:ring-1 focus:ring-accent"
              >
                {SCHEDULE_TYPES.map((s) => (
                  <option key={s.value} value={s.value}>{s.label}</option>
                ))}
              </select>
            </div>
          </div>
          <div className="flex justify-end gap-2">
            <button
              onClick={() => setShowCreate(false)}
              className="text-body text-text-secondary hover:text-text-primary px-3 py-1.5"
            >
              Cancel
            </button>
            <button
              onClick={() => createMutation.mutate(form)}
              disabled={createMutation.isPending}
              className="rounded-lg px-3 py-1.5 text-body font-medium bg-accent text-white hover:bg-accent/90 disabled:opacity-50 transition-colors"
            >
              {createMutation.isPending ? "Creating…" : "Create"}
            </button>
          </div>
        </div>
      )}

      {isLoading && (
        <p className="text-body text-text-secondary py-8 text-center">Loading schedules…</p>
      )}

      {!isLoading && schedules.length === 0 && (
        <div className="flex flex-col items-center gap-3 py-12">
          <Clock className="h-12 w-12 text-text-secondary opacity-40" />
          <p className="text-body text-text-secondary">No scheduled reports configured.</p>
          <p className="text-caption text-text-secondary/60">Click "Add Schedule" to set up your first automated report.</p>
        </div>
      )}

      <div className="space-y-2">
        {schedules.map((s) => {
          const reportLabel = REPORT_TYPES.find((t) => t.value === s.report_type)?.label ?? s.report_type;
          return (
            <div
              key={s.id}
              className={clsx(
                "rounded-xl border bg-surface p-4 transition-opacity",
                s.enabled ? "border-border" : "border-border/50 opacity-60"
              )}
              data-testid="schedule-item"
            >
              <div className="flex items-center justify-between gap-3">
                <div className="flex items-center gap-3 flex-1 min-w-0">
                  <Clock className="h-4 w-4 text-accent flex-shrink-0" />
                  <div className="flex-1 min-w-0">
                    <div className="flex items-center gap-2 flex-wrap">
                      <span className="text-body font-semibold text-text-primary dark:text-gray-100">
                        {reportLabel}
                      </span>
                      <span className={clsx("rounded-full px-2 py-0.5 text-xs font-medium capitalize", scheduleColor(s.schedule_type))}>
                        {s.schedule_type}
                      </span>
                      {!s.enabled && (
                        <span className="rounded-full bg-border text-text-secondary text-xs px-2 py-0.5">
                          Paused
                        </span>
                      )}
                    </div>
                    <p className="text-caption text-text-secondary mt-0.5">
                      Created {format(new Date(s.created_at), "dd MMM yyyy")}
                      {s.last_run && ` · Last run ${format(new Date(s.last_run), "dd MMM yyyy, HH:mm")}`}
                      {s.next_run && ` · Next run ${format(new Date(s.next_run), "dd MMM yyyy")}`}
                    </p>
                  </div>
                </div>

                <div className="flex items-center gap-1 flex-shrink-0">
                  <button
                    onClick={() => toggleMutation.mutate({ id: s.id, enabled: !s.enabled })}
                    className="text-text-secondary hover:text-accent p-1 rounded transition-colors"
                    title={s.enabled ? "Pause schedule" : "Enable schedule"}
                  >
                    {s.enabled ? (
                      <ToggleRight className="h-5 w-5 text-accent" />
                    ) : (
                      <ToggleLeft className="h-5 w-5" />
                    )}
                  </button>
                  <button
                    onClick={() => deleteMutation.mutate(s.id)}
                    disabled={deleteMutation.isPending}
                    className="text-text-secondary hover:text-critical p-1 rounded transition-colors"
                    title="Delete schedule"
                  >
                    <Trash2 className="h-4 w-4" />
                  </button>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
